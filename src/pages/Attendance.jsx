import {
  useEffect,
  useRef,
  useState,
} from "react";

import UserAvatar
  from "../components/UserAvatar";

import {
  CalendarCheck,
  CheckCircle2,
  QrCode,
  ShieldCheck,
  XCircle,
} from "lucide-react";

import {
  useNavigate,
  useParams,
} from "react-router-dom";

import {
  supabase,
} from "../lib/supabase";

import Sidebar
  from "../components/Sidebar";

import NotificationBell
  from "../components/NotificationBell";

import "./Attendance.css";


function Attendance() {
  const navigate =
    useNavigate();


  const {
    token,
  } = useParams();


  const automaticAttempt =
    useRef(false);


  const [
    ,
    setCurrentUser,
  ] = useState(null);


  const [
    profile,
    setProfile,
  ] = useState(null);


  const [
    history,
    setHistory,
  ] = useState([]);


  const [
    groups,
    setGroups,
  ] = useState([]);


  const [
    sessions,
    setSessions,
  ] = useState([]);


  const [
    loading,
    setLoading,
  ] = useState(true);


  const [
    checkingIn,
    setCheckingIn,
  ] = useState(false);


  const [
    successMessage,
    setSuccessMessage,
  ] = useState("");


  const [
    errorMessage,
    setErrorMessage,
  ] = useState("");


  useEffect(() => {
    loadPage();
  }, []);


  async function loadPage() {
    setLoading(true);


    const {
      data: {
        user,
      },
      error,
    } =
      await supabase.auth.getUser();


    if (
      error ||
      !user
    ) {
      navigate("/");

      return;
    }


    setCurrentUser(
      user
    );


    const {
      data: profileData,
    } =
      await supabase
        .from("profiles")
        .select(
          `
          id,
          full_name,
          campus_id,
          programme,
          role
          `
        )
        .eq(
          "id",
          user.id
        )
        .maybeSingle();


    setProfile(
      profileData
    );


    await loadHistory(
      user.id
    );


    setLoading(false);


    if (
      token &&
      !automaticAttempt.current
    ) {
      automaticAttempt.current =
        true;


      await checkInByToken(
        token,
        user.id
      );
    }
  }


  async function loadHistory(
    studentId
  ) {
    const {
      data,
      error,
    } =
      await supabase
        .from(
          "attendance_records"
        )
        .select("*")
        .eq(
          "student_id",
          studentId
        )
        .order(
          "created_at",
          {
            ascending: false,
          }
        );


    if (error) {
      console.error(
        error
      );

      return;
    }


    const loadedHistory =
      data || [];


    setHistory(
      loadedHistory
    );


    const groupIds =
      [
        ...new Set(
          loadedHistory.map(
            (record) =>
              record.group_id
          )
        ),
      ];


    const sessionIds =
      [
        ...new Set(
          loadedHistory.map(
            (record) =>
              record.session_id
          )
        ),
      ];


    if (
      groupIds.length >
      0
    ) {
      const {
        data: groupData,
      } =
        await supabase
          .from(
            "course_groups"
          )
          .select(
            `
            id,
            name,
            course_code
            `
          )
          .in(
            "id",
            groupIds
          );


      setGroups(
        groupData || []
      );
    }


    if (
      sessionIds.length >
      0
    ) {
      const {
        data: sessionData,
      } =
        await supabase
          .from(
            "attendance_sessions"
          )
          .select(
            `
            id,
            started_at,
            expires_at,
            closed_at
            `
          )
          .in(
            "id",
            sessionIds
          );


      setSessions(
        sessionData || []
      );
    }
  }


  async function checkInByToken(
    attendanceToken,
    studentId
  ) {
    setCheckingIn(
      true
    );


    setSuccessMessage("");
    setErrorMessage("");


    const {
      data,
      error,
    } =
      // QR codes generated by the professor (work for 30 seconds)
      await supabase.rpc(
        "check_in_attendance_by_qr",
        {
          input_code:
            attendanceToken,
        }
      );


    if (error) {
      setErrorMessage(
        /permission denied/i.test(error.message)
          ? "This QR code is out of date. Scan the code on your professor's screen again."
          : error.message
      );

      setCheckingIn(
        false
      );

      return;
    }


    const result =
      data?.[0];


    setSuccessMessage(
      `Attendance recorded successfully for ${result?.group_name || "your class"}.`
    );


    await loadHistory(
      studentId
    );


    setCheckingIn(
      false
    );


    navigate(
      "/attendance",
      {
        replace: true,
      }
    );
  }


  function getGroup(
    groupId
  ) {
    return groups.find(
      (group) =>
        group.id ===
        groupId
    );
  }


  function getSession(
    sessionId
  ) {
    return sessions.find(
      (session) =>
        session.id ===
        sessionId
    );
  }


  const presentCount =
    history.filter(
      (record) =>
        record.status ===
        "present"
    ).length;


  const absentCount =
    history.filter(
      (record) =>
        record.status ===
        "absent"
    ).length;


  const attendancePercentage =
    history.length === 0
      ? 0
      : Math.round(
          (
            presentCount /
            history.length
          ) *
            100
        );


  const fullName =
    profile?.full_name ||
    "Student";


  if (loading) {
    return (
      <div className="student-att-loading">

        <CalendarCheck
          size={45}
        />

        <p>
          Loading attendance...
        </p>

      </div>
    );
  }


  return (
    <div className="student-att-page">

      <Sidebar />


      <main className="student-att-main">

        <header className="student-att-topbar">

          <div>

            <CalendarCheck
              size={20}
            />

            Attendance

          </div>


          <div className="student-att-profile">

            <NotificationBell />


          <UserAvatar
          size={46}
          />

            <div>

              <strong>
                {fullName}
              </strong>

              <small>
                {profile?.campus_id}
              </small>

            </div>

          </div>

        </header>


        <div className="student-att-content">

          <div className="student-att-header">

            <h1>
              Attendance
            </h1>

            <p>
              Check in only when your professor starts an attendance session.
            </p>

          </div>


          {successMessage && (

            <div className="student-att-success">

              <CheckCircle2
                size={18}
              />

              {successMessage}

            </div>

          )}


          {errorMessage && (

            <div className="student-att-error">

              <XCircle
                size={18}
              />

              {errorMessage}

            </div>

          )}


          <section className="student-att-checkin">

            <div className="student-att-checkin-heading">

              <div className="student-att-checkin-icon">

                <QrCode
                  size={27}
                />

              </div>


              <div>

                <h2>
                  Check In
                </h2>

                <p>
                  Open your phone camera and scan the QR code on your professor&apos;s screen. Each code works for 30 seconds.
                </p>

              </div>

            </div>


            {checkingIn && (
              <p className="student-att-checking" role="status">
                Checking you in...
              </p>
            )}


            <div className="student-att-security">

              <ShieldCheck
                size={19}
              />


              <p>
                You cannot manually mark yourself Present or Absent. Attendance is available only while your professor's session is active.
              </p>

            </div>

          </section>


          <section className="student-att-stats">

            <div>

              <span className="percentage">
                {attendancePercentage}%
              </span>

              <small>
                Attendance Rate
              </small>

            </div>


            <div>

              <span className="present">
                {presentCount}
              </span>

              <small>
                Present
              </small>

            </div>


            <div>

              <span className="absent">
                {absentCount}
              </span>

              <small>
                Absent
              </small>

            </div>


            <div>

              <span>
                {history.length}
              </span>

              <small>
                Total Sessions
              </small>

            </div>

          </section>


          <section className="student-att-history">

            <div className="student-att-history-header">

              <div>

                <h2>
                  Attendance History
                </h2>

                <p>
                  Your attendance records from professor-created sessions.
                </p>

              </div>

            </div>


            {history.length ===
            0 ? (

              <div className="student-att-empty">

                <CalendarCheck
                  size={45}
                />

                <h3>
                  No attendance records yet
                </h3>

                <p>
                  Your attendance will appear here after your professor starts a session.
                </p>

              </div>

            ) : (

              <div className="student-att-list">

                <div className="student-att-table-head">

                  <span>
                    Class
                  </span>

                  <span>
                    Date
                  </span>

                  <span>
                    Check-in
                  </span>

                  <span>
                    Status
                  </span>

                </div>


                {history.map(
                  (record) => {

                    const group =
                      getGroup(
                        record.group_id
                      );


                    const attendanceSession =
                      getSession(
                        record.session_id
                      );


                    return (

                      <div
                        className="student-att-row"
                        key={
                          record.id
                        }
                      >

                        <div>

                          <strong>
                            {group?.name ||
                              "Class"}
                          </strong>

                          <small>
                            {group?.course_code ||
                              ""}
                          </small>

                        </div>


                        <span>

                          {attendanceSession
                            ?.started_at
                            ? new Date(
                                attendanceSession.started_at
                              ).toLocaleDateString(
                                "en-GB",
                                {
                                  day:
                                    "2-digit",
                                  month:
                                    "short",
                                  year:
                                    "numeric",
                                }
                              )
                            : "-"}

                        </span>


                        <span>

                          {record.checked_in_at
                            ? new Date(
                                record.checked_in_at
                              ).toLocaleTimeString(
                                [],
                                {
                                  hour:
                                    "2-digit",
                                  minute:
                                    "2-digit",
                                }
                              )
                            : "—"}

                        </span>


                        <span
                          className={`student-att-status ${record.status}`}
                        >

                          {record.status ===
                          "present"
                            ? "Present"
                            : "Absent"}

                        </span>

                      </div>

                    );
                  }
                )}

              </div>

            )}

          </section>

        </div>

      </main>

    </div>
  );
}


export default Attendance;